#!/usr/bin/env node
// licensegate: what the licences of your npm dependencies mean for the way you ship the code.
// npx github:agustinnb/licensegate [dir] --mode saas|distributed|library|internal [--prod] [--fail-on review]
//   [--allow pkg,pkg] [--sbom sbom.cdx.json] [--notices THIRD_PARTY_NOTICES.txt] [--json out.json]
// Exit 1 when a dependency blocks the chosen mode (or needs review, with --fail-on review). Runs offline; no code leaves
// the machine. This is an inventory and a risk flag, not legal advice.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { parse, verdict, MODES } from './spdx.mjs';
import { inventory } from './detect.mjs';

export const VERSION = '0.1.0';
const WHY = {
  network: 'network copyleft: users who reach the program over a network can ask for its source',
  strong: 'strong copyleft: shipping it inside your program can require releasing your program under the same licence',
  weak: 'weak copyleft: changes to that library (and, for LGPL, how it is linked or bundled) carry obligations',
  restricted: 'source-available or non-commercial terms: check the commercial use clause',
  unknown: 'no recognisable licence found: ask the author or replace the package',
};

export function analyse(dir, { mode = 'saas', prod = false, allow = [] } = {}) {
  const inv = inventory(dir, { prod });
  const rows = inv.packages.map((p) => {
    const allowed = allow.includes(p.name) || allow.includes(`${p.name}@${p.version}`);
    const v = verdict(parse(p.license), mode);
    return { ...p, verdict: allowed ? 'ok' : v.v, category: v.cat, chosen: v.id, allowed };
  });
  const count = (k) => rows.filter((r) => r.verdict === k).length;
  return { mode, from: inv.from, rows, summary: { total: rows.length, ok: count('ok'), review: count('review'), block: count('block') } };
}

export function cyclonedx(dir, res) {
  const pj = (() => { try { return JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')); } catch { return {}; } })();
  const purl = (n, v) => `pkg:npm/${n.startsWith('@') ? '%40' + n.slice(1) : n}@${v}`;
  const lic = (s) => (!s ? [] : /\s(OR|AND|WITH)\s/i.test(s) ? [{ expression: s }] : [{ license: { id: s } }]);
  return {
    bomFormat: 'CycloneDX', specVersion: '1.5', serialNumber: 'urn:uuid:' + crypto.randomUUID(), version: 1,
    metadata: { timestamp: new Date().toISOString(), tools: { components: [{ type: 'application', name: 'licensegate', version: VERSION }] },
      component: { type: 'application', name: pj.name || path.basename(path.resolve(dir)), version: pj.version || '0.0.0' } },
    components: res.rows.map((r) => ({ type: 'library', name: r.name, version: r.version, purl: purl(r.name, r.version), 'bom-ref': purl(r.name, r.version), licenses: lic(r.license),
      ...(r.dev ? { scope: 'optional' } : {}) })),
  };
}

export function notices(dir, res) {
  const head = `THIRD-PARTY SOFTWARE NOTICES\nGenerated by licensegate ${VERSION} on ${new Date().toISOString().slice(0, 10)} from ${res.from}.\n`;
  const parts = res.rows.filter((r) => !r.dev).sort((a, b) => a.name.localeCompare(b.name)).map((r) => {
    let text = '';
    const d = path.join(dir, r.path);
    try { const f = fs.readdirSync(d).find((n) => /^(licen[cs]e|copying|notice)(\.(md|txt))?$/i.test(n)); if (f) text = fs.readFileSync(path.join(d, f), 'utf8').trim(); } catch {}
    return `\n${'-'.repeat(72)}\n${r.name}@${r.version}\nLicense: ${r.license || 'UNKNOWN'}\n${text ? '\n' + text + '\n' : ''}`;
  });
  return head + parts.join('');
}

function args(argv) {
  const o = { dir: '.', mode: 'saas', prod: false, failOn: 'block', allow: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i], next = () => argv[++i];
    if (a === '--mode') o.mode = next();
    else if (a === '--prod') o.prod = true;
    else if (a === '--fail-on') o.failOn = next();
    else if (a === '--allow') o.allow = String(next() || '').split(',').map((s) => s.trim()).filter(Boolean);
    else if (a === '--sbom') o.sbom = next();
    else if (a === '--notices') o.notices = next();
    else if (a === '--json') o.json = next();
    else if (a === '-h' || a === '--help') o.help = true;
    else if (a === '-v' || a === '--version') o.version = true;
    else if (!a.startsWith('-')) o.dir = a;
  }
  return o;
}

const HELP = `licensegate ${VERSION}: what your npm dependencies' licences mean for how you ship.

  npx github:agustinnb/licensegate [dir] --mode saas|distributed|library|internal

  --mode       how the code reaches people (default saas)
  --prod       skip devDependencies
  --fail-on    block (default) or review
  --allow      comma list of packages you have cleared (name or name@version)
  --sbom F     write a CycloneDX 1.5 SBOM
  --notices F  write THIRD_PARTY_NOTICES with every licence text
  --json F     write the full result

Not legal advice: an inventory and a risk flag. Nothing leaves your machine.`;

export async function main(argv = process.argv.slice(2), log = console.log) {
  const o = args(argv);
  if (o.help) { log(HELP); return 0; }
  if (o.version) { log(VERSION); return 0; }
  if (!MODES.includes(o.mode)) { log(`Unknown --mode ${o.mode}. Use one of: ${MODES.join(', ')}`); return 2; }
  const res = analyse(o.dir, o);
  if (!res.from) {
    let pj = null; try { pj = JSON.parse(fs.readFileSync(path.join(o.dir, 'package.json'), 'utf8')); } catch {}
    if (pj && !Object.keys({ ...pj.dependencies, ...(o.prod ? {} : pj.devDependencies), ...pj.optionalDependencies }).length) { log(`licensegate ${VERSION} · mode ${o.mode} · no dependencies, nothing to check`); return 0; }
    log('No package-lock.json or node_modules found. Run npm install (or npm i --package-lock-only) first.'); return 2; }
  const flagged = res.rows.filter((r) => r.verdict !== 'ok').sort((a, b) => (a.verdict === 'block' ? -1 : 1) - (b.verdict === 'block' ? -1 : 1));
  log(`licensegate ${VERSION} · mode ${o.mode}${o.prod ? ' · production only' : ''} · ${res.summary.total} packages from ${res.from}`);
  for (const r of flagged) log(`  ${r.verdict === 'block' ? 'BLOCK ' : 'REVIEW'} ${r.name}@${r.version}  ${r.license || 'no licence'}${r.dev ? '  (dev)' : ''}\n         ${WHY[r.category] || ''}`);
  log(`  ${res.summary.ok} ok · ${res.summary.review} to review · ${res.summary.block} blocking`);
  if (o.sbom) { fs.writeFileSync(o.sbom, JSON.stringify(cyclonedx(o.dir, res), null, 2)); log(`  SBOM → ${o.sbom}`); }
  if (o.notices) { fs.writeFileSync(o.notices, notices(o.dir, res)); log(`  Notices → ${o.notices}`); }
  if (o.json) fs.writeFileSync(o.json, JSON.stringify(res, null, 2));
  log('  Not legal advice. Grey cases (linking, plug-ins, dual licences) say REVIEW on purpose.');
  return res.summary.block || (o.failOn === 'review' && res.summary.review) ? 1 : 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main().then((code) => process.exit(code));
}
